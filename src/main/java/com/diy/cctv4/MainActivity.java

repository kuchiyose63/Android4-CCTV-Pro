package com.diy.cctv4;

import android.app.Activity;
import android.content.ComponentName;
import android.content.Context;
import android.content.Intent;
import android.content.ServiceConnection;
import android.os.Build;
import android.os.Bundle;
import android.os.IBinder;
import android.view.SurfaceHolder;
import android.view.SurfaceView;
import android.view.View;
import android.view.WindowManager;
import android.widget.Button;
import android.widget.TextView;

public class MainActivity extends Activity implements SurfaceHolder.Callback, CctvService.StatusListener {

    private CctvService cctvService;
    private boolean isBound = false;
    private SurfaceHolder surfaceHolder;
    private TextView tvIpAddress;
    private TextView tvStatus;
    private Button btnRecord;
    private View blackOverlay;

    private final ServiceConnection connection = new ServiceConnection() {
        @Override
        public void onServiceConnected(ComponentName name, IBinder service) {
            CctvService.LocalBinder binder = (CctvService.LocalBinder) service;
            cctvService = binder.getService();
            isBound = true;
            cctvService.setStatusListener(MainActivity.this);
            if (surfaceHolder != null && surfaceHolder.getSurface() != null && surfaceHolder.getSurface().isValid()) {
                cctvService.attachPreviewHolder(surfaceHolder);
            }
        }

        @Override
        public void onServiceDisconnected(ComponentName name) {
            isBound = false;
            cctvService = null;
        }
    };

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        setContentView(R.layout.activity_main);

        tvIpAddress = findViewById(R.id.tvIpAddress);
        tvStatus = findViewById(R.id.tvStatus);
        btnRecord = findViewById(R.id.btnRecord);
        blackOverlay = findViewById(R.id.blackOverlay);
        Button btnSwitchCam = findViewById(R.id.btnSwitchCam);
        Button btnDimScreen = findViewById(R.id.btnDimScreen);

        SurfaceView surfaceView = findViewById(R.id.surfaceView);
        surfaceHolder = surfaceView.getHolder();
        surfaceHolder.addCallback(this);
        surfaceHolder.setType(SurfaceHolder.SURFACE_TYPE_PUSH_BUFFERS);

        Intent serviceIntent = new Intent(this, CctvService.class);
        if (Build.VERSION.SDK_INT >= 26) {
            startForegroundService(serviceIntent);
        } else {
            startService(serviceIntent);
        }

        btnRecord.setOnClickListener(v -> {
            if (isBound && cctvService != null) cctvService.toggleRecording();
        });

        btnSwitchCam.setOnClickListener(v -> {
            if (isBound && cctvService != null) cctvService.switchCamera();
        });

        btnDimScreen.setOnClickListener(v -> {
            blackOverlay.setVisibility(View.VISIBLE);
            WindowManager.LayoutParams params = getWindow().getAttributes();
            params.screenBrightness = 0.01f;
            getWindow().setAttributes(params);
        });

        blackOverlay.setOnClickListener(v -> {
            blackOverlay.setVisibility(View.GONE);
            WindowManager.LayoutParams params = getWindow().getAttributes();
            params.screenBrightness = -1.0f;
            getWindow().setAttributes(params);
        });
    }

    @Override
    protected void onStart() {
        super.onStart();
        bindService(new Intent(this, CctvService.class), connection, Context.BIND_AUTO_CREATE);
    }

    @Override
    protected void onStop() {
        super.onStop();
        if (isBound) {
            if (cctvService != null) {
                cctvService.attachPreviewHolder(null);
                cctvService.setStatusListener(null);
            }
            unbindService(connection);
            isBound = false;
        }
    }

    @Override
    public void surfaceCreated(SurfaceHolder holder) {
        if (isBound && cctvService != null) {
            cctvService.attachPreviewHolder(holder);
        }
    }

    @Override
    public void surfaceChanged(SurfaceHolder holder, int format, int width, int height) {}

    @Override
    public void surfaceDestroyed(SurfaceHolder holder) {
        if (isBound && cctvService != null) {
            cctvService.attachPreviewHolder(null);
        }
    }

    @Override
    public void onStatusChanged(final String ipUrl, final String statusText, final boolean isRecording) {
        runOnUiThread(() -> {
            tvIpAddress.setText(ipUrl);
            tvStatus.setText(statusText);
            btnRecord.setText(isRecording ? "Stop Rekam" : "Mulai Rekam");
        });
    }
}
