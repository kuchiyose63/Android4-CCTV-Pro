package com.diy.cctv4;

import android.graphics.ImageFormat;
import android.graphics.Rect;
import android.graphics.YuvImage;
import android.media.AudioFormat;
import android.media.AudioRecord;
import android.media.MediaCodec;
import android.media.MediaCodecInfo;
import android.media.MediaCodecList;
import android.media.MediaFormat;
import android.media.MediaMuxer;
import android.media.MediaRecorder;

import java.io.BufferedOutputStream;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.RandomAccessFile;
import java.nio.ByteBuffer;
import java.util.ArrayList;
import java.util.List;

@SuppressWarnings("deprecation")
public interface VideoRecorder {
    void addYuvFrame(byte[] nv21Data, int jpegQuality) throws Exception;
    void close() throws Exception;

    class Mp4AvcRecorder implements VideoRecorder {
        private static final int SAMPLE_RATE = 16000;
        private static final int AUDIO_BITRATE = 64000;

        private final MediaCodec videoEncoder;
        private MediaCodec audioEncoder;
        private AudioRecord audioRecord;
        private final MediaMuxer muxer;
        private final Object muxerLock = new Object();

        private final int width;
        private final int height;
        private final int colorFormat;
        private final byte[] convertedBuffer;

        private int videoTrackIndex = -1;
        private int audioTrackIndex = -1;
        private boolean hasAudio = false;
        private boolean muxerStarted = false;
        private volatile boolean isRecordingAudio = false;
        private Thread audioThread;

        private final long startTimeNanos;
        private final MediaCodec.BufferInfo videoBufferInfo = new MediaCodec.BufferInfo();

        public Mp4AvcRecorder(File outputFile, int width, int height, int fps) throws Exception {
            this.width = width;
            this.height = height;
            this.convertedBuffer = new byte[width * height * 3 / 2];
            this.startTimeNanos = System.nanoTime();

            // 1. Setup Video Encoder (H.264)
            MediaCodecInfo codecInfo = selectCodec("video/avc");
            if (codecInfo == null) throw new IOException("No AVC codec");
            this.colorFormat = selectColorFormat(codecInfo, "video/avc");

            MediaFormat videoFormat = MediaFormat.createVideoFormat("video/avc", width, height);
            videoFormat.setInteger(MediaFormat.KEY_COLOR_FORMAT, colorFormat);
            videoFormat.setInteger(MediaFormat.KEY_BIT_RATE, 2000000);
            videoFormat.setInteger(MediaFormat.KEY_FRAME_RATE, fps);
            videoFormat.setInteger(MediaFormat.KEY_I_FRAME_INTERVAL, 2);

            videoEncoder = MediaCodec.createByCodecName(codecInfo.getName());
            videoEncoder.configure(videoFormat, null, null, MediaCodec.CONFIGURE_FLAG_ENCODE);
            videoEncoder.start();

            muxer = new MediaMuxer(outputFile.getAbsolutePath(), MediaMuxer.OutputFormat.MUXER_OUTPUT_MPEG_4);

            // 2. Setup Audio Encoder (AAC) + Mikrofon (opsional, jika izin aktif)
            try {
                int minBufSize = AudioRecord.getMinBufferSize(SAMPLE_RATE, AudioFormat.CHANNEL_IN_MONO, AudioFormat.ENCODING_PCM_16BIT);
                if (minBufSize > 0) {
                    audioRecord = new AudioRecord(MediaRecorder.AudioSource.MIC, SAMPLE_RATE, AudioFormat.CHANNEL_IN_MONO, AudioFormat.ENCODING_PCM_16BIT, minBufSize * 2);
                    if (audioRecord.getState() == AudioRecord.STATE_INITIALIZED) {
                        MediaFormat audioFormat = MediaFormat.createAudioFormat("audio/mp4a-latm", SAMPLE_RATE, 1);
                        audioFormat.setInteger(MediaFormat.KEY_AAC_PROFILE, MediaCodecInfo.CodecProfileLevel.AACObjectLC);
                        audioFormat.setInteger(MediaFormat.KEY_BIT_RATE, AUDIO_BITRATE);
                        audioFormat.setInteger(MediaFormat.KEY_MAX_INPUT_SIZE, minBufSize * 2);

                        audioEncoder = MediaCodec.createEncoderByType("audio/mp4a-latm");
                        audioEncoder.configure(audioFormat, null, null, MediaCodec.CONFIGURE_FLAG_ENCODE);
                        audioEncoder.start();

                        hasAudio = true;
                        startAudioThread(minBufSize);
                    } else {
                        audioRecord.release();
                        audioRecord = null;
                    }
                }
            } catch (Exception e) {
                hasAudio = false;
                if (audioRecord != null) { try { audioRecord.release(); } catch (Exception ignored) {} audioRecord = null; }
                if (audioEncoder != null) { try { audioEncoder.release(); } catch (Exception ignored) {} audioEncoder = null; }
            }
        }

        private void startAudioThread(final int bufferSize) {
            isRecordingAudio = true;
            audioRecord.startRecording();
            audioThread = new Thread(() -> {
                byte[] pcmBuffer = new byte[bufferSize];
                MediaCodec.BufferInfo audioInfo = new MediaCodec.BufferInfo();
                while (isRecordingAudio) {
                    int readBytes = audioRecord.read(pcmBuffer, 0, pcmBuffer.length);
                    if (readBytes > 0) {
                        try {
                            ByteBuffer[] inBuffers = audioEncoder.getInputBuffers();
                            int inIdx = audioEncoder.dequeueInputBuffer(5000);
                            if (inIdx >= 0) {
                                ByteBuffer inBuf = inBuffers[inIdx];
                                inBuf.clear();
                                int len = Math.min(inBuf.capacity(), readBytes);
                                inBuf.put(pcmBuffer, 0, len);
                                long ptsUsec = (System.nanoTime() - startTimeNanos) / 1000L;
                                audioEncoder.queueInputBuffer(inIdx, 0, len, ptsUsec, 0);
                            }
                            drainAudioEncoder(audioInfo, false);
                        } catch (Exception ignored) {}
                    }
                }
                try {
                    int inIdx = audioEncoder.dequeueInputBuffer(5000);
                    if (inIdx >= 0) {
                        audioEncoder.queueInputBuffer(inIdx, 0, 0, (System.nanoTime() - startTimeNanos) / 1000L, MediaCodec.BUFFER_FLAG_END_OF_STREAM);
                    }
                    drainAudioEncoder(audioInfo, true);
                } catch (Exception ignored) {}
            });
            audioThread.start();
        }

        private void drainAudioEncoder(MediaCodec.BufferInfo info, boolean endOfStream) {
            ByteBuffer[] outBuffers = audioEncoder.getOutputBuffers();
            while (true) {
                int outIdx = audioEncoder.dequeueOutputBuffer(info, 2000);
                if (outIdx == MediaCodec.INFO_TRY_AGAIN_LATER) {
                    if (!endOfStream) break;
                } else if (outIdx == MediaCodec.INFO_OUTPUT_BUFFERS_CHANGED) {
                    outBuffers = audioEncoder.getOutputBuffers();
                } else if (outIdx == MediaCodec.INFO_OUTPUT_FORMAT_CHANGED) {
                    synchronized (muxerLock) {
                        if (audioTrackIndex == -1) {
                            audioTrackIndex = muxer.addTrack(audioEncoder.getOutputFormat());
                            checkStartMuxerLocked();
                        }
                    }
                } else if (outIdx >= 0) {
                    ByteBuffer encodedData = outBuffers[outIdx];
                    if ((info.flags & MediaCodec.BUFFER_FLAG_CODEC_CONFIG) != 0) info.size = 0;
                    if (info.size != 0) {
                        synchronized (muxerLock) {
                            if (muxerStarted && audioTrackIndex != -1) {
                                encodedData.position(info.offset);
                                encodedData.limit(info.offset + info.size);
                                muxer.writeSampleData(audioTrackIndex, encodedData, info);
                            }
                        }
                    }
                    audioEncoder.releaseOutputBuffer(outIdx, false);
                    if ((info.flags & MediaCodec.BUFFER_FLAG_END_OF_STREAM) != 0) break;
                }
            }
        }

        private void checkStartMuxerLocked() {
            if (muxerStarted) return;
            if (videoTrackIndex != -1 && (!hasAudio || audioTrackIndex != -1)) {
                muxer.start();
                muxerStarted = true;
            }
        }

        private static MediaCodecInfo selectCodec(String mimeType) {
            int numCodecs = MediaCodecList.getCodecCount();
            for (int i = 0; i < numCodecs; i++) {
                MediaCodecInfo codecInfo = MediaCodecList.getCodecInfoAt(i);
                if (!codecInfo.isEncoder()) continue;
                for (String type : codecInfo.getSupportedTypes()) {
                    if (type.equalsIgnoreCase(mimeType)) return codecInfo;
                }
            }
            return null;
        }

        private static int selectColorFormat(MediaCodecInfo codecInfo, String mimeType) {
            MediaCodecInfo.CodecCapabilities caps = codecInfo.getCapabilitiesForType(mimeType);
            for (int format : caps.colorFormats) {
                if (format == MediaCodecInfo.CodecCapabilities.COLOR_FormatYUV420SemiPlanar ||
                    format == MediaCodecInfo.CodecCapabilities.COLOR_FormatYUV420Planar) {
                    return format;
                }
            }
            return MediaCodecInfo.CodecCapabilities.COLOR_FormatYUV420SemiPlanar;
        }

        private byte[] convertNv21(byte[] nv21) {
            int frameSize = width * height;
            System.arraycopy(nv21, 0, convertedBuffer, 0, frameSize);
            if (colorFormat == MediaCodecInfo.CodecCapabilities.COLOR_FormatYUV420SemiPlanar) {
                for (int i = frameSize; i < frameSize + frameSize / 2; i += 2) {
                    convertedBuffer[i] = nv21[i + 1];
                    convertedBuffer[i + 1] = nv21[i];
                }
            } else {
                int uIndex = frameSize;
                int vIndex = frameSize + frameSize / 4;
                for (int i = frameSize; i < frameSize + frameSize / 2; i += 2) {
                    convertedBuffer[vIndex++] = nv21[i];
                    convertedBuffer[uIndex++] = nv21[i + 1];
                }
            }
            return convertedBuffer;
        }

        @Override
        public void addYuvFrame(byte[] nv21Data, int jpegQuality) {
            ByteBuffer[] inputBuffers = videoEncoder.getInputBuffers();
            int inputBufferIndex = videoEncoder.dequeueInputBuffer(5000);
            if (inputBufferIndex >= 0) {
                ByteBuffer inputBuffer = inputBuffers[inputBufferIndex];
                inputBuffer.clear();
                byte[] frameData = convertNv21(nv21Data);
                int length = Math.min(inputBuffer.capacity(), frameData.length);
                inputBuffer.put(frameData, 0, length);
                long ptsUsec = (System.nanoTime() - startTimeNanos) / 1000L;
                videoEncoder.queueInputBuffer(inputBufferIndex, 0, length, ptsUsec, 0);
            }
            drainVideoEncoder(false);
        }

        private void drainVideoEncoder(boolean endOfStream) {
            if (endOfStream) {
                int inIdx = videoEncoder.dequeueInputBuffer(5000);
                if (inIdx >= 0) {
                    videoEncoder.queueInputBuffer(inIdx, 0, 0, (System.nanoTime() - startTimeNanos) / 1000L, MediaCodec.BUFFER_FLAG_END_OF_STREAM);
                }
            }
            ByteBuffer[] outputBuffers = videoEncoder.getOutputBuffers();
            while (true) {
                int outIdx = videoEncoder.dequeueOutputBuffer(videoBufferInfo, 2000);
                if (outIdx == MediaCodec.INFO_TRY_AGAIN_LATER) {
                    if (!endOfStream) break;
                } else if (outIdx == MediaCodec.INFO_OUTPUT_BUFFERS_CHANGED) {
                    outputBuffers = videoEncoder.getOutputBuffers();
                } else if (outIdx == MediaCodec.INFO_OUTPUT_FORMAT_CHANGED) {
                    synchronized (muxerLock) {
                        if (videoTrackIndex == -1) {
                            videoTrackIndex = muxer.addTrack(videoEncoder.getOutputFormat());
                            checkStartMuxerLocked();
                        }
                    }
                } else if (outIdx >= 0) {
                    ByteBuffer encodedData = outputBuffers[outIdx];
                    if ((videoBufferInfo.flags & MediaCodec.BUFFER_FLAG_CODEC_CONFIG) != 0) videoBufferInfo.size = 0;
                    if (videoBufferInfo.size != 0) {
                        synchronized (muxerLock) {
                            if (muxerStarted && videoTrackIndex != -1) {
                                encodedData.position(videoBufferInfo.offset);
                                encodedData.limit(videoBufferInfo.offset + videoBufferInfo.size);
                                muxer.writeSampleData(videoTrackIndex, encodedData, videoBufferInfo);
                            }
                        }
                    }
                    videoEncoder.releaseOutputBuffer(outIdx, false);
                    if ((videoBufferInfo.flags & MediaCodec.BUFFER_FLAG_END_OF_STREAM) != 0) break;
                }
            }
        }

        @Override
        public void close() {
            isRecordingAudio = false;
            if (audioThread != null) {
                try { audioThread.join(1000); } catch (Exception ignored) {}
            }
            if (audioRecord != null) {
                try { audioRecord.stop(); audioRecord.release(); } catch (Exception ignored) {}
            }
            if (audioEncoder != null) {
                try { audioEncoder.stop(); audioEncoder.release(); } catch (Exception ignored) {}
            }
            try { drainVideoEncoder(true); } catch (Exception ignored) {}
            try { videoEncoder.stop(); videoEncoder.release(); } catch (Exception ignored) {}
            synchronized (muxerLock) {
                try { if (muxerStarted) muxer.stop(); muxer.release(); } catch (Exception ignored) {}
            }
        }
    }

    class SimpleMjpegAviWriter implements VideoRecorder {
        private final File file;
        private final BufferedOutputStream bos;
        private final int width;
        private final int height;
        private final int fps;
        private int frameCount = 0;
        private long moviDataSize = 0;
        private final List<Integer> frameSizes = new ArrayList<>();

        public SimpleMjpegAviWriter(File file, int width, int height, int fps) throws IOException {
            this.file = file;
            this.width = width;
            this.height = height;
            this.fps = fps;
            this.bos = new BufferedOutputStream(new FileOutputStream(file), 32768);
            bos.write(new byte[224]);
        }

        @Override
        public void addYuvFrame(byte[] nv21Data, int jpegQuality) throws IOException {
            YuvImage yuv = new YuvImage(nv21Data, ImageFormat.NV21, width, height, null);
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            yuv.compressToJpeg(new Rect(0, 0, width, height), jpegQuality, out);
            byte[] jpegData = out.toByteArray();

            int len = jpegData.length;
            int pad = (len % 2 != 0) ? 1 : 0;
            writeFourCC("00dc");
            writeIntLE(len);
            bos.write(jpegData);
            if (pad > 0) bos.write(0);

            frameSizes.add(len);
            frameCount++;
            moviDataSize += (8 + len + pad);
        }

        @Override
        public void close() throws IOException {
            long idxSize = frameCount * 16L;
            writeFourCC("idx1");
            writeIntLE((int) idxSize);
            int offset = 4;
            for (int size : frameSizes) {
                writeFourCC("00dc");
                writeIntLE(0x10);
                writeIntLE(offset);
                writeIntLE(size);
                int pad = (size % 2 != 0) ? 1 : 0;
                offset += (8 + size + pad);
            }
            bos.flush();
            bos.close();

            RandomAccessFile raf = new RandomAccessFile(file, "rw");
            raf.seek(0);
            long totalRiffSize = 216 + moviDataSize + 8 + idxSize;

            writeRafFourCC(raf, "RIFF");
            writeRafIntLE(raf, (int) totalRiffSize);
            writeRafFourCC(raf, "AVI ");
            writeRafFourCC(raf, "LIST");
            writeRafIntLE(raf, 192);
            writeRafFourCC(raf, "hdrl");
            writeRafFourCC(raf, "avih");
            writeRafIntLE(raf, 56);
            writeRafIntLE(raf, 1000000 / fps);
            writeRafIntLE(raf, 1000000);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, 0x10);
            writeRafIntLE(raf, frameCount);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, 1);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, width);
            writeRafIntLE(raf, height);
            for (int i = 0; i < 4; i++) writeRafIntLE(raf, 0);

            writeRafFourCC(raf, "LIST");
            writeRafIntLE(raf, 116);
            writeRafFourCC(raf, "strl");
            writeRafFourCC(raf, "strh");
            writeRafIntLE(raf, 56);
            writeRafFourCC(raf, "vids");
            writeRafFourCC(raf, "MJPG");
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, 1);
            writeRafIntLE(raf, fps);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, frameCount);
            writeRafIntLE(raf, 0);
            writeRafIntLE(raf, -1);
            writeRafIntLE(raf, 0);
            writeRafShortLE(raf, (short) 0);
            writeRafShortLE(raf, (short) 0);
            writeRafShortLE(raf, (short) width);
            writeRafShortLE(raf, (short) height);

            writeRafFourCC(raf, "strf");
            writeRafIntLE(raf, 40);
            writeRafIntLE(raf, 40);
            writeRafIntLE(raf, width);
            writeRafIntLE(raf, height);
            writeRafShortLE(raf, (short) 1);
            writeRafShortLE(raf, (short) 24);
            writeRafFourCC(raf, "MJPG");
            writeRafIntLE(raf, width * height * 3);
            for (int i = 0; i < 4; i++) writeRafIntLE(raf, 0);

            writeRafFourCC(raf, "LIST");
            writeRafIntLE(raf, (int) (moviDataSize + 4));
            writeRafFourCC(raf, "movi");
            raf.close();
        }

        private void writeFourCC(String s) throws IOException { bos.write(s.getBytes("US-ASCII")); }
        private void writeIntLE(int v) throws IOException {
            bos.write(v & 0xFF); bos.write((v >> 8) & 0xFF); bos.write((v >> 16) & 0xFF); bos.write((v >> 24) & 0xFF);
        }
        private void writeRafFourCC(RandomAccessFile raf, String s) throws IOException { raf.write(s.getBytes("US-ASCII")); }
        private void writeRafIntLE(RandomAccessFile raf, int v) throws IOException {
            raf.write(v & 0xFF); raf.write((v >> 8) & 0xFF); raf.write((v >> 16) & 0xFF); raf.write((v >> 24) & 0xFF);
        }
        private void writeRafShortLE(RandomAccessFile raf, short v) throws IOException {
            raf.write(v & 0xFF); raf.write((v >> 8) & 0xFF);
        }
    }
}
